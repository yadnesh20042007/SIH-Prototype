import type { Metadata } from 'next';
import { notFound } from 'next/navigation';

import { DatabaseNotFoundError } from '@/lib/db/errors';
import { getPublicReportVerification } from '@/lib/services/report-verification.service';

export const metadata: Metadata = {
  title: 'Verify NAWI Test Report',
  description: 'Public verification of a report generated by the NAWI R76 testing platform.',
};

function display(value: string): string { return value.replaceAll('_', ' '); }
function date(value: string | null): string {
  if (!value) return 'Not recorded';
  return new Intl.DateTimeFormat('en-GB', { dateStyle: 'medium', timeStyle: 'short', timeZone: 'UTC' }).format(new Date(value)) + ' UTC';
}

export default async function VerifyReportPage({ params }: { params: Promise<{ qrVerificationId: string }> }) {
  const { qrVerificationId } = await params;
  let report;
  try {
    report = await getPublicReportVerification(qrVerificationId.trim());
  } catch (error) {
    if (error instanceof DatabaseNotFoundError) notFound();
    throw error;
  }

  const isRevoked = report.status === 'REVOKED';
  const isNotValid = report.status === 'NOT_VALID';
  const isFail = report.complianceResult === 'FAIL';
  const isRetest = report.complianceResult === 'REQUIRES_RETEST';
  const isIncomplete = report.complianceResult === 'INCOMPLETE';
  const isNotAvailable = report.complianceResult === 'NOT_AVAILABLE';
  const isPass = report.complianceResult === 'PASS';

  let tone: 'valid' | 'fail' | 'warn' | 'invalid' = 'valid';
  let badgeText = '';
  let title = '';
  let summaryText = '';

  if (isRevoked) {
    tone = 'invalid';
    badgeText = 'REPORT REVOKED';
    title = 'Report Revoked';
    summaryText = 'This test report has been revoked and is no longer valid.';
  } else if (isNotValid) {
    tone = 'invalid';
    badgeText = 'REPORT NOT VALID';
    title = 'Report Not Valid';
    summaryText = 'This report reference does not correspond to an approved session.';
  } else if (isFail) {
    tone = 'fail';
    badgeText = 'FINALIZED NON-COMPLIANT TEST REPORT';
    title = 'Non-Compliant Test Report (Verified)';
    summaryText = 'This record verifies an authentic finalized test report where the instrument failed one or more OIML R 76 compliance criteria. Administrative approval confirms completion of testing; it does NOT certify the instrument as compliant.';
  } else if (isRetest) {
    tone = 'warn';
    badgeText = 'AUTHENTIC REPORT — REQUIRES RETEST';
    title = 'Authentic Report (Requires Retest)';
    summaryText = 'This record verifies an authentic test report where compliance evaluation indicates a mandatory retest is required before compliance can be certified. Administrative approval confirms completion of testing; it does NOT certify the instrument as compliant.';
  } else if (isIncomplete) {
    tone = 'warn';
    badgeText = 'AUTHENTIC REPORT — INCOMPLETE TESTING';
    title = 'Authentic Report (Incomplete Testing)';
    summaryText = 'This record verifies an authentic test report, but mandatory applicable testing is incomplete or not all required tests were evaluated. Administrative approval confirms completion of testing; it does NOT certify the instrument as compliant.';
  } else if (isNotAvailable) {
    tone = 'warn';
    badgeText = 'AUTHENTIC REPORT — STATUS NOT AVAILABLE';
    title = 'Authentic Report (Status Not Available)';
    summaryText = 'This record verifies an authentic test report, but no technical test results are recorded. Administrative approval confirms completion of testing; it does NOT certify the instrument as compliant.';
  } else if (isPass) {
    tone = 'valid';
    badgeText = 'VERIFIED COMPLIANT TEST REPORT';
    title = 'Verified Test Report (Compliant)';
    summaryText = 'This record matches an authentic report generated by this NAWI testing platform from an approved session where all evaluated tests complied with OIML R 76 requirements.';
  } else {
    tone = 'warn';
    badgeText = 'AUTHENTIC REPORT — PENDING COMPLIANCE';
    title = 'Authentic Report (Non-Certified)';
    summaryText = 'This record verifies an authentic test report. Administrative approval confirms completion of testing; it does NOT certify the instrument as compliant.';
  }

  const borderClass =
    tone === 'valid'
      ? 'border-[#ABEFC6]'
      : tone === 'fail'
      ? 'border-[#FECDCA]'
      : tone === 'warn'
      ? 'border-[#FEDF89]'
      : 'border-[#FDA29B]';

  const headerBgClass =
    tone === 'valid'
      ? 'bg-[#ECFDF3]'
      : tone === 'fail'
      ? 'bg-[#FEF3F2]'
      : tone === 'warn'
      ? 'bg-[#FFFAEB]'
      : 'bg-[#FEF3F2]';

  const badgeTextClass =
    tone === 'valid'
      ? 'text-[#067647]'
      : tone === 'fail'
      ? 'text-[#B42318]'
      : tone === 'warn'
      ? 'text-[#B54708]'
      : 'text-[#B42318]';

  const titleTextClass =
    tone === 'valid'
      ? 'text-[#065F46]'
      : tone === 'fail'
      ? 'text-[#991B1B]'
      : tone === 'warn'
      ? 'text-[#B54708]'
      : 'text-[#991B1B]';

  return (
    <main className="min-h-screen bg-[#F7F9FB] px-4 py-8 sm:px-6">
      <div className="mx-auto max-w-3xl">
        <header className="mb-5 flex items-center gap-3 border-b border-[#D9E2EC] bg-white px-5 py-4">
          <div className="flex h-10 w-10 items-center justify-center rounded bg-[#0A66C2] text-lg font-bold text-white">R76</div>
          <div><p className="m-0 text-[0.92rem] font-bold text-[#1D2226]">NAWI Report Verification</p><p className="m-0 mt-0.5 text-[0.68rem] text-[#667085]">Public verification record</p></div>
        </header>
        <section className={`overflow-hidden rounded-lg border bg-white shadow-[0_1px_3px_rgba(16,24,40,0.08)] ${borderClass}`}>
          <div className={`px-6 py-5 ${headerBgClass}`}>
            <p className={`m-0 text-[0.64rem] font-bold uppercase tracking-[0.12em] ${badgeTextClass}`}>{badgeText}</p>
            <h1 className={`m-0 mt-1 text-2xl font-bold ${titleTextClass}`}>{title}</h1>
            <p className="m-0 mt-2 text-[0.76rem] leading-relaxed text-[#475467]">{summaryText}</p>
          </div>
          <div className="grid gap-6 p-6">
            <section><h2 className="m-0 border-b border-[#D9E2EC] pb-2 text-[0.72rem] font-bold uppercase tracking-[0.09em] text-[#344054]">Report</h2><dl className="mt-3 grid grid-cols-1 gap-3 text-[0.75rem] sm:grid-cols-2"><div><dt className="text-[#667085]">Reference</dt><dd className="m-0 mt-0.5 font-bold text-[#1D2226]">{report.reportReference}</dd></div><div><dt className="text-[#667085]">Version</dt><dd className="m-0 mt-0.5 font-semibold">{report.reportVersion}</dd></div><div><dt className="text-[#667085]">Generated</dt><dd className="m-0 mt-0.5 font-semibold">{date(report.issuedAt)}</dd></div><div><dt className="text-[#667085]">Final approval</dt><dd className="m-0 mt-0.5 font-semibold">{date(report.finalApprovalAt)}</dd></div></dl></section>
            <section><h2 className="m-0 border-b border-[#D9E2EC] pb-2 text-[0.72rem] font-bold uppercase tracking-[0.09em] text-[#344054]">Instrument</h2><dl className="mt-3 grid grid-cols-2 gap-3 text-[0.75rem] sm:grid-cols-3"><div><dt className="text-[#667085]">Manufacturer</dt><dd className="m-0 mt-0.5 font-semibold">{report.manufacturer}</dd></div><div><dt className="text-[#667085]">Model</dt><dd className="m-0 mt-0.5 font-semibold">{report.model}</dd></div><div><dt className="text-[#667085]">Type</dt><dd className="m-0 mt-0.5 font-semibold">{display(report.instrumentType)}</dd></div><div><dt className="text-[#667085]">Accuracy class</dt><dd className="m-0 mt-0.5 font-semibold">{report.accuracyClass}</dd></div><div><dt className="text-[#667085]">Max / Min</dt><dd className="m-0 mt-0.5 font-semibold">{report.max} / {report.min} kg</dd></div><div><dt className="text-[#667085]">e / d</dt><dd className="m-0 mt-0.5 font-semibold">{report.e} / {report.d} kg</dd></div></dl></section>
            <section><h2 className="m-0 border-b border-[#D9E2EC] pb-2 text-[0.72rem] font-bold uppercase tracking-[0.09em] text-[#344054]">Decision</h2><dl className="mt-3 grid grid-cols-1 gap-3 text-[0.75rem] sm:grid-cols-3"><div><dt className="text-[#667085]">Ruleset</dt><dd className="m-0 mt-0.5 font-semibold">{report.ruleset}</dd></div><div><dt className="text-[#667085]">Persisted compliance result</dt><dd className="m-0 mt-0.5 font-bold">{display(report.complianceResult)}</dd></div><div><dt className="text-[#667085]">Approval status</dt><dd className="m-0 mt-0.5 font-bold">{display(report.approvalStatus)}</dd></div></dl></section>
          </div>
          <footer className="border-t border-[#D9E2EC] bg-[#FBFCFD] px-6 py-3 text-[0.66rem] leading-relaxed text-[#667085]">This platform verification confirms the authenticity of the test record. It does not state or imply that OIML or a statutory authority certified the report.</footer>
        </section>
      </div>
    </main>
  );
}
